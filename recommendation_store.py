"""Local, per-candidate-per-JD recommendation and interview history."""

from __future__ import annotations

import threading
import uuid
from datetime import datetime, timezone
from pg_store import connect


LOCK = threading.RLock()


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _connect():
    return connect()


def ensure_schema() -> None:
    with _connect() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS recommendations (
        id TEXT PRIMARY KEY,
        job_id TEXT NOT NULL,
        candidate_id TEXT NOT NULL,
        owner_id TEXT NOT NULL DEFAULT '',
        candidate_name TEXT NOT NULL DEFAULT '',
        candidate_profile TEXT NOT NULL DEFAULT '',
        stars INTEGER NOT NULL,
        reason TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT '待反馈',
        interest TEXT NOT NULL DEFAULT '',
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL,
        UNIQUE(job_id, candidate_id)
    )""")
        db.execute("""CREATE TABLE IF NOT EXISTS feedback_events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        recommendation_id TEXT NOT NULL,
        from_status TEXT NOT NULL,
        to_status TEXT NOT NULL,
        changed_at TEXT NOT NULL
    )""")


def get(recommendation_id: str) -> dict | None:
    with LOCK, _connect() as db:
        row = db.execute("SELECT * FROM recommendations WHERE id = %s", (recommendation_id,)).fetchone()
        return dict(row) if row else None


def find(job_id: str, candidate_id: str) -> dict | None:
    with LOCK, _connect() as db:
        row = db.execute("SELECT * FROM recommendations WHERE job_id = %s AND candidate_id = %s", (job_id, candidate_id)).fetchone()
        return dict(row) if row else None


def all_rows() -> list[dict]:
    with LOCK, _connect() as db:
        return [dict(row) for row in db.execute("SELECT * FROM recommendations ORDER BY created_at, id")]


def create(job_id: str, candidate_id: str, owner_id: str, name: str, profile: str, stars: int, reason: str, *, legacy_id: str = '', status: str = '待反馈', interest: str = '') -> dict:
    with LOCK, _connect() as db:
        now = _now()
        record_id = legacy_id or 'local_' + uuid.uuid4().hex
        return dict(db.execute("""INSERT INTO recommendations VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (job_id, candidate_id) DO UPDATE SET id = recommendations.id RETURNING *""",
            (record_id, job_id, candidate_id, owner_id, name, profile, stars, reason, status, interest, now, now)).fetchone())


def set_status(recommendation_id: str, status: str, interest: str | None = None) -> dict:
    with LOCK, _connect() as db:
        previous = db.execute("SELECT status FROM recommendations WHERE id = %s FOR UPDATE", (recommendation_id,)).fetchone()
        if not previous:
            raise ValueError("推荐记录不存在")
        if interest is None:
            db.execute("UPDATE recommendations SET status = %s, updated_at = %s WHERE id = %s", (status, _now(), recommendation_id))
        else:
            db.execute("UPDATE recommendations SET status = %s, interest = %s, updated_at = %s WHERE id = %s", (status, interest, _now(), recommendation_id))
        if previous["status"] != status:
            db.execute("INSERT INTO feedback_events (recommendation_id, from_status, to_status, changed_at) VALUES (%s, %s, %s, %s)", (recommendation_id, previous["status"], status, _now()))
        row = db.execute("SELECT * FROM recommendations WHERE id = %s", (recommendation_id,)).fetchone()
        return dict(row)
